export function uniqueTargetKey(target: ReturnType<typeof union>): string {
  const b = bounds(target.flat(2) as Poly);
  return JSON.stringify(
    target.map((poly) =>
      poly.map((ring) =>
        ring.map(([x, y]) => [+(x - b.x).toFixed(5), +(y - b.y).toFixed(5)]),
      ),
    ),
  );
}
